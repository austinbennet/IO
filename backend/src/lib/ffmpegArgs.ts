import path from 'node:path';

export interface Rung {
  name: string; // e.g. "720p"
  height: number;
  videoKbps: number;
  audioKbps: number;
}

export type SourceSpec =
  | { type: 'URL'; url: string }
  | { type: 'LAVFI_TEST'; pattern: 'testsrc2' | 'smptebars' };

export interface HlsOptions {
  source: SourceSpec;
  outDir: string;
  ladder: Rung[];
  segmentSeconds: number;
  listSize: number;
  preset: string;
  fps: number;
  /** Hardware encoders are opt-in only: 'software' (libx264) is the default and always available. */
  encoder: 'software' | 'nvenc' | 'qsv' | 'vaapi';
}

/**
 * Parses HLS_LADDER like "1080p:1080:8000:192,720p:720:5000:160,360p:360:1200:128".
 * Rejects unsafe or nonsensical values so the operator gets a precise error at startup.
 */
export function parseLadder(spec: string): Rung[] {
  const rungs = spec.split(',').map((s) => s.trim()).filter(Boolean).map((entry) => {
    const [name, height, videoKbps, audioKbps] = entry.split(':');
    const rung = { name, height: Number(height), videoKbps: Number(videoKbps), audioKbps: Number(audioKbps) };
    if (!/^[a-z0-9]{2,8}$/i.test(name ?? '')) throw new Error(`Invalid rung name in HLS_LADDER: ${entry}`);
    if (![240, 360, 480, 540, 720, 1080].includes(rung.height)) throw new Error(`Unsupported rung height ${height} (use 240/360/480/540/720/1080)`);
    if (!(rung.videoKbps >= 200 && rung.videoKbps <= 20000)) throw new Error(`Video bitrate out of range in ${entry}`);
    if (!(rung.audioKbps >= 64 && rung.audioKbps <= 320)) throw new Error(`Audio bitrate out of range in ${entry}`);
    return rung;
  });
  if (rungs.length === 0) throw new Error('HLS_LADDER must contain at least one rung');
  if (rungs.length > 4) throw new Error('HLS_LADDER supports at most 4 variants per channel on this host profile');
  return rungs;
}

export function sourceInputArgs(source: SourceSpec, fps: number): { args: string[]; videoInput: string; audioInput: string } {
  if (source.type === 'LAVFI_TEST') {
    // Generated by FFmpeg itself: a real encodable test signal with a moving timer and a 1 kHz tone.
    const video = source.pattern === 'smptebars' ? `smptebars=size=1920x1080:rate=${fps}` : `testsrc2=size=1280x720:rate=${fps}`;
    return {
      args: ['-re', '-f', 'lavfi', '-i', video, '-re', '-f', 'lavfi', '-i', 'sine=frequency=1000:sample_rate=48000'],
      videoInput: '0:v:0',
      audioInput: '1:a:0',
    };
  }
  const isHttp = /^https?:/i.test(source.url);
  const args = isHttp
    ? ['-reconnect', '1', '-reconnect_streamed', '1', '-reconnect_delay_max', '5', '-rw_timeout', '15000000']
    : ['-rw_timeout', '15000000'];
  args.push('-i', source.url);
  return { args, videoInput: '0:v:0', audioInput: '0:a:0?' };
}

/**
 * Builds the full FFmpeg command for an adaptive-bitrate HLS output.
 * Produces: master.m3u8 + <rung>/index.m3u8 + <rung>/segNNNNN.ts (MPEG-TS segments, sliding window).
 */
export function buildHlsArgs(opts: HlsOptions): string[] {
  const { args: inputArgs, videoInput, audioInput } = sourceInputArgs(opts.source, opts.fps);
  const n = opts.ladder.length;
  const gop = opts.fps * opts.segmentSeconds;

  const splitLabels = opts.ladder.map((_, i) => `[s${i}]`).join('');
  const filters = [`[${videoInput}]split=${n}${splitLabels}`];
  opts.ladder.forEach((r, i) => {
    filters.push(`[s${i}]scale=-2:${r.height}:flags=bicubic,format=yuv420p[v${i}]`);
  });

  const args: string[] = ['-hide_banner', '-loglevel', 'warning', '-nostats', '-progress', 'pipe:1', ...inputArgs];
  args.push('-filter_complex', filters.join(';'));

  const encoderArgs = (i: number): string[] => {
    // Software is the default. Hardware variants are only selected when explicitly configured.
    const codec = opts.encoder === 'nvenc' ? 'h264_nvenc' : opts.encoder === 'qsv' ? 'h264_qsv' : opts.encoder === 'vaapi' ? 'h264_vaapi' : 'libx264';
    const r = opts.ladder[i];
    const v = [
      '-map', `[v${i}]`,
      `-c:v:${i}`, codec,
      ...(codec === 'libx264' ? ['-preset', opts.preset, '-profile:v:' + i, 'main'] : []),
      `-b:v:${i}`, `${r.videoKbps}k`,
      `-maxrate:v:${i}`, `${Math.round(r.videoKbps * 1.2)}k`,
      `-bufsize:v:${i}`, `${r.videoKbps * 2}k`,
      `-g:v:${i}`, String(gop),
      `-keyint_min:v:${i}`, String(gop),
      `-sc_threshold:v:${i}`, '0',
      '-map', audioInput,
      `-c:a:${i}`, 'aac',
      `-b:a:${i}`, `${r.audioKbps}k`,
      `-ac:a:${i}`, '2',
      `-ar:a:${i}`, '48000',
    ];
    return v;
  };
  for (let i = 0; i < n; i++) args.push(...encoderArgs(i));

  const varMap = opts.ladder.map((r, i) => `v:${i},a:${i},name:${r.name}`).join(' ');
  args.push(
    '-f', 'hls',
    '-hls_time', String(opts.segmentSeconds),
    '-hls_list_size', String(opts.listSize),
    '-hls_flags', 'delete_segments+independent_segments+program_date_time+temp_file',
    '-hls_segment_type', 'mpegts',
    '-hls_segment_filename', path.join(opts.outDir, '%v', 'seg%05d.ts'),
    '-master_pl_name', 'master.m3u8',
    '-var_stream_map', varMap,
    path.join(opts.outDir, '%v', 'index.m3u8'),
  );
  return args;
}

export function buildRecordingArgs(source: SourceSpec, outFile: string, fps = 25): string[] {
  const { args: inputArgs } = sourceInputArgs(source, fps);
  const codecArgs = source.type === 'LAVFI_TEST'
    ? ['-map', '0:v:0', '-map', '1:a:0', '-c:v', 'libx264', '-preset', 'ultrafast', '-b:v', '3000k', '-c:a', 'aac', '-b:a', '128k']
    : ['-map', '0:v:0?', '-map', '0:a:0?', '-c', 'copy'];
  return ['-hide_banner', '-loglevel', 'warning', '-nostats', '-progress', 'pipe:1', ...inputArgs, ...codecArgs, '-f', 'mpegts', outFile];
}
